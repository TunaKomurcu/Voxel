def load_persona(key: str) -> tuple[str, str, str]:
    """Returns (display_name, system_prompt, greeting) read straight from
    the real agents/<name>.jsonc — never modified for this test."""
    path = lib.AGENT_DIR / f"{AGENT_FILES[key]}.jsonc"
    data = lib.parse_jsonc(path.read_text(encoding="utf-8"))
    return key.capitalize(), data["system_prompt"], data["greeting"]


def _estimate_tokens(text: str) -> int:
    """Rough, tokenizer-free approximation (~1.3 tokens/word for English) —
    only used for the pre-run estimate; the real run reports actual usage
    from the gateway's response instead."""
    return max(1, round(len(text.split()) * 1.3))


def format_transcript(transcript: list[dict]) -> str:
    return "\n".join(f'{m["speaker"]}: {m["text"]}' for m in transcript)


def build_messages(character_prompt: str, transcript: list[dict], speaker_label: str) -> list[dict]:
    instruction = (
        f"Conversation so far:\n\n{format_transcript(transcript)}\n\n"
        f"Continue the conversation as {speaker_label}, in character per your "
        f"instructions above. Reply with ONLY your next line of spoken "
        f"dialogue — no stage directions, no quotation marks, no speaker "
        f"label, no meta-commentary."
    )
    return [
        {"role": "system", "content": character_prompt},
        {"role": "user", "content": instruction},
    ]


def estimate_cost(combos: list[tuple[str, str]], turns: int) -> dict:
    total_input = 0
    total_output = 0
    for persona_key, archetype_key in combos:
        _, persona_prompt, greeting = load_persona(persona_key)
        founder_prompt = FOUNDER_ARCHETYPES[archetype_key]
        transcript = [{"speaker": persona_key.capitalize(), "text": greeting}]
        for _ in range(turns):
            for prompt, label in ((founder_prompt, "the founder"), (persona_prompt, persona_key.capitalize())):
                messages = build_messages(prompt, transcript, label)
                input_text = messages[0]["content"] + messages[1]["content"]
                total_input += _estimate_tokens(input_text)
                total_output += MAX_TOKENS_PER_REPLY  # upper bound: assume full budget used
                transcript.append({"speaker": label if label != "the founder" else "Founder",
                                    "text": "x" * 40})  # placeholder, only length matters downstream
    cost = (total_input / 1_000_000) * PRICE_PER_1M_INPUT + (total_output / 1_000_000) * PRICE_PER_1M_OUTPUT
    return {
        "combos": len(combos),
        "turns_per_combo": turns,
        "calls_per_combo": turns * 2,
        "total_calls": len(combos) * turns * 2,
        "est_input_tokens": total_input,
        "est_output_tokens_upper_bound": total_output,
        "est_cost_usd": round(cost, 4),
    }


def simulate(persona_key: str, archetype_key: str, turns: int, max_tokens: int) -> dict:
    persona_name, persona_prompt, greeting = load_persona(persona_key)
    founder_prompt = FOUNDER_ARCHETYPES[archetype_key]
    transcript = [{"speaker": persona_name, "text": greeting}]
    usage = {"prompt_tokens": 0, "completion_tokens": 0}
    for _ in range(turns):
        for prompt, label, is_persona in (
            (founder_prompt, "the founder", False),
            (persona_prompt, persona_name, True),
        ):
            messages = build_messages(prompt, transcript, label)
            response = judge._llm_gateway_chat_with_retry(MODEL, messages, max_tokens)
            line = response["choices"][0]["message"]["content"].strip().strip('"')
            u = response.get("usage") or {}
            usage["prompt_tokens"] += u.get("prompt_tokens", 0)
            usage["completion_tokens"] += u.get("completion_tokens", 0)
            transcript.append({"speaker": persona_name if is_persona else "Founder", "text": line})
            time.sleep(PAUSE_BETWEEN_CALLS)  # every call, not just once per combo — this is what was missing
    cost = (usage["prompt_tokens"] / 1_000_000) * PRICE_PER_1M_INPUT + \
           (usage["completion_tokens"] / 1_000_000) * PRICE_PER_1M_OUTPUT
    return {
        "persona": persona_key,
        "persona_name": persona_name,
        "archetype": archetype_key,
        "turns": turns,
        "transcript": transcript,
        "usage": usage,
        "cost_usd": round(cost, 6),
    }


def run_all(combos: list[tuple[str, str]], turns: int, max_tokens: int) -> None:
    TRANSCRIPTS_DIR.mkdir(exist_ok=True)
    total_cost = 0.0
    failures = []
    for i, (persona_key, archetype_key) in enumerate(combos, 1):
        print(f"[{i}/{len(combos)}] {persona_key} x {archetype_key} ... ", end="", flush=True)
        try:
            result = simulate(persona_key, archetype_key, turns, max_tokens)
        except Exception as err:  # keep going across combos even if one fails
            print(f"FAILED: {err}")
            failures.append((persona_key, archetype_key, str(err)))
            continue
        out_path = TRANSCRIPTS_DIR / f"{persona_key}__{archetype_key}.json"
        out_path.write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding="utf-8")
        total_cost += result["cost_usd"]
        print(f"ok (${result['cost_usd']:.5f}, {result['usage']['prompt_tokens']}+"
              f"{result['usage']['completion_tokens']} tok) -> {out_path.name}")
        time.sleep(PAUSE_BETWEEN_CALLS)

    print(f"\nDone. Total actual cost: ${total_cost:.4f} across {len(combos) - len(failures)}"
          f"/{len(combos)} combinations.")
    if failures:
        print(f"{len(failures)} failed:")
        for persona_key, archetype_key, err in failures:
            print(f"  {persona_key} x {archetype_key}: {err}")


def all_combos() -> list[tuple[str, str]]:
    return [(p, a) for p in AGENT_FILES for a in FOUNDER_ARCHETYPES]


def parse_only(spec: str) -> list[tuple[str, str]]:
    combos = []
    for pair in spec.split(","):
        persona_key, archetype_key = pair.split(":")
        combos.append((persona_key.strip(), archetype_key.strip()))
    return combos


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run", action="store_true", help="actually call the LLM Gateway (costs money)")
    parser.add_argument("--turns", type=int, default=DEFAULT_TURNS, help=f"exchanges per combo (default {DEFAULT_TURNS})")
    parser.add_argument("--max-tokens", type=int, default=MAX_TOKENS_PER_REPLY,
                         help=f"max tokens per generated line (default {MAX_TOKENS_PER_REPLY})")
    parser.add_argument("--only", type=str, default=None,
                         help="comma-separated persona:archetype pairs, e.g. marcus:scattered,grace:pushback")
    args = parser.parse_args()

    combos = parse_only(args.only) if args.only else all_combos()

    estimate = estimate_cost(combos, args.turns)
    print("Cost estimate (before any API calls):")
    print(f"  combinations: {estimate['combos']} ({estimate['turns_per_combo']} turns each, "
          f"{estimate['calls_per_combo']} calls/combo, {estimate['total_calls']} calls total)")
    print(f"  est. input tokens:  ~{estimate['est_input_tokens']:,}")
    print(f"  est. output tokens: ~{estimate['est_output_tokens_upper_bound']:,} (upper bound, "
          f"assumes every reply uses the full {args.max_tokens}-token budget)")
    print(f"  est. cost:          ~${estimate['est_cost_usd']:.4f} "
          f"(at ${PRICE_PER_1M_INPUT}/1M in, ${PRICE_PER_1M_OUTPUT}/1M out, global routing)")

    if not args.run:
        print("\nDry run only — pass --run to actually call the gateway.")
        return

    lib.load_env()
    lib.required("ASSEMBLYAI_API_KEY", "get one at https://www.assemblyai.com/dashboard/api-keys")
    print()
    run_all(combos, args.turns, args.max_tokens)


if __name__ == "__main__":
    main()
