#!/usr/bin/env python3
"""Text-only self-play: each of the 4 real personas (agents/*.jsonc, used
unmodified) against 7 synthetic "founder" behavior profiles, both sides
generated by the LLM Gateway (qwen3.5-4b-32k-fast — the same cheap model
judge.py uses). Cheap and fast because it skips the Voice Agent API/audio
entirely, but for that same reason it can only test PERSONA CONSISTENCY
(does the character hold, does it react sensibly to the founder's behavior)
— it produces no real audio timestamps, so it says nothing about actual
barge-in/turn-detection behavior. That still needs a live call.

    python tests/self_play.py                 # estimate cost only (no calls)
    python tests/self_play.py --run            # actually call the gateway
    python tests/self_play.py --run --turns 4  # override exchange count
    python tests/self_play.py --run --only marcus:scattered,grace:pushback

Saves one JSON transcript per combination to tests/self_play_transcripts/.
"""

