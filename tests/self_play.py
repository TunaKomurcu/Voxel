import json
import sys
import time
from pathlib import Path
from typing import Optional

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import judge  # noqa: E402
import lib  # noqa: E402

MODEL = judge.JUDGE_MODEL  # qwen3.5-4b-32k-fast — same model, same pricing tier
PRICE_PER_1M_INPUT = 0.10   # USD, global routing — see AssemblyAI's Qwen3.5 4B announcement
PRICE_PER_1M_OUTPUT = 0.50  # USD, global routing (in-region is +10%, not counted here)

TRANSCRIPTS_DIR = Path(__file__).resolve().parent / "self_play_transcripts"
PAUSE_BETWEEN_CALLS = 45.0  # seconds — between EVERY gateway call. Calibrated live against this
# account's actual LLM Gateway limit (2026-09-16): 2s and 10s spacing both still hit persistent
# 429s across multiple consecutive calls (worse than judge_eval.py's 2s, which only ever fires 3
# calls per fixture, never a sustained run). 45s is a large safety margin chosen after repeated
# calibration attempts, prioritizing a completed run over speed — a 40-combo/5-turn run takes
# ~5 hours at this pace. Revisit downward only after confirming the account's real quota (e.g.
# via the AssemblyAI dashboard), not by re-guessing through more trial-and-error calls.

DEFAULT_TURNS = 5          # exchanges: founder line + persona line = 1 exchange
MAX_TOKENS_PER_REPLY = 80  # both personas and founders speak in 1-3 short sentences

# name -> agents/<name>.jsonc stem
